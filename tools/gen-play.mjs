// Writes the native play scripts (tests/native/*.play) from the content:
// each board is filled by keyboard as a player would (the arrows move the
// focus ring from the centre cell, the number keys pick the colour, Enter
// fills), in a snake through the rows, so the scripts follow the generated
// levels exactly. Run after a content change: `node tools/gen-play.mjs`.
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateLevel, journeyLevel, journeyStages, tutorialLessons, tierSpec } from '../js/content.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'tests', 'native');
mkdirSync(out, { recursive: true });

/** Plays one board by keyboard: the focus ring, the selected colour and the filled cells. */
class Board {
  constructor(level, lines) {
    this.level = level;
    this.lines = lines;
    this.focus = Math.floor(level.targets.length / 2);
    this.selected = null;
    this.fills = new Array(level.targets.length).fill(0);
  }
  key(code) { this.lines.push(`key ${code} 1`, 'frames 1'); }
  moveTo(cell) {
    const { w, h } = this.level;
    let x = this.focus % w, y = Math.floor(this.focus / w);
    const tx = cell % w, ty = Math.floor(cell / w);
    while (x !== tx) { const right = ((tx - x) + w) % w <= w / 2; this.key(right ? 'ArrowRight' : 'ArrowLeft'); x = (x + (right ? 1 : -1) + w) % w; }
    while (y !== ty) { const down = ((ty - y) + h) % h <= h / 2; this.key(down ? 'ArrowDown' : 'ArrowUp'); y = (y + (down ? 1 : -1) + h) % h; }
    this.focus = cell;
  }
  select(c) { if (this.selected !== c) { this.key(`Digit${c + 1}`); this.selected = c; } }
  /** Fill `cell` with its own colour (selecting it first). */
  fill(cell) {
    this.moveTo(cell);
    this.select(this.level.targets[cell]);
    this.key('Enter');
    this.fills[cell] = 1;
  }
  /** Press Enter on `cell` with colour `c` selected, which is not its own (a slip). */
  slip(cell, c) { this.moveTo(cell); this.select(c); this.key('Enter'); }
  /** The cells in a snake through the rows (optionally one colour's only), unfilled ones. */
  snake(color = null) {
    const { w, h, targets } = this.level;
    const cells = [];
    for (let y = 0; y < h; y++) for (let k = 0; k < w; k++) {
      const x = y % 2 ? w - 1 - k : k, i = y * w + x;
      if (!this.fills[i] && (color == null || targets[i] === color)) cells.push(i);
    }
    return cells;
  }
  fillAll(color = null) { for (const c of this.snake(color)) this.fill(c); }
}

const header = (title, lines) => [`# Generated by tools/gen-play.mjs: ${title}`, ...lines.map((l) => `# ${l}`), 'until 300 Color Haven', 'frames 30'];
function write(name, lines) { writeFileSync(join(out, name), lines.join('\n') + '\n'); console.log(`${name}: ${lines.length} lines`); }

// ---- Learn: Play on a new profile runs the three lessons, then the title.
{
  const L = header('Play on a new profile: the three Learn lessons by keyboard and taps on the coach banner, to the title.', [
    'Lesson 1 picks color 1 and fills every "1"; lesson 2 picks color 2, slips once and fills two "2"s;',
    'lesson 3 finishes its piece to the results, and Play again ends the tutorial.']);
  const lessons = tutorialLessons();
  L.push('click =Play', 'until 120 Pick color 1 in the palette', 'frames 10');
  let b = new Board(lessons[0].level, L);
  b.select(0);
  L.push('until 30 Now tap a region');
  b.fill(b.snake(0)[0]);
  L.push('until 30 Fill every remaining');
  b.fillAll(0);
  L.push('until 30 That is the whole loop', 'frames 10', 'click tap this message to continue');
  L.push('until 120 Select color 2', 'frames 10');
  b = new Board(lessons[1].level, L);
  b.select(1);
  L.push('until 30 Regions only accept their own number');
  b.slip(b.snake(0)[0], 1);
  L.push('until 30 That region needs color 1', 'until 30 Fill two regions marked');
  const twos = b.snake(1);
  b.fill(twos[0]); b.fill(twos[1]);
  L.push('until 30 Made a slip?', 'frames 10', 'save learn-banner', 'click tap this message to continue');
  L.push('until 120 Finish this small piece', 'frames 10');
  b = new Board(lessons[2].level, L);
  b.fillAll();
  L.push('until 240 Illustration complete', 'frames 30', 'save learn-results', 'click =Play again');
  L.push('until 120 Tutorial complete', 'expect Fill numbered regions', 'frames 10', 'save learn-title');
  write('learn.play', L);
}

// ---- Journey stage 1 with a slip, an undo and a hint, to the results and the next stage.
{
  const stage = journeyStages()[0];
  const level = journeyLevel(stage);
  const L = header(`journey stage 1 (${stage.title}) from the map, with a slip, an undo and a hint, to the results.`, [
    'Then Next stage opens stage 2.']);
  L.push('click =Journey', 'until 60 Every 8th stage is a mastery test', 'frames 10', 'save journey-map', `click Stage 1, ${stage.title}`);
  L.push('until 120 Par time', 'frames 30');
  const b = new Board(level, L);
  const first = b.snake()[0];
  b.slip(first, (level.targets[first] + 1) % level.paletteSize);
  L.push('until 30 That region needs color');
  b.fill(first);
  b.key('KeyU');
  b.fills[first] = 0;
  L.push('frames 5', 'expect 0 / 64');
  b.key('KeyH');
  L.push('until 30 Hint placed a region', 'frames 5', 'expect 1 / 64', 'save journey-round');
  // The hint filled the first cell of the preferred colour: replay it in the model.
  const prefer = b.selected;
  const hinted = level.targets.findIndex((t) => t === prefer);
  b.fills[hinted] = 1;
  b.fillAll();
  L.push('until 240 Illustration complete', 'frames 30', 'save journey-results', 'click =Next stage', 'until 120 Wide Meadow', 'frames 20', 'save journey-2');
  write('journey-first-stage.play', L);
}

// ---- The Strict ledger challenge (ranked, move limit), to the results and its local leaderboard.
{
  const t = tierSpec(3);
  const level = generateLevel({
    id: 'challenge-moves', seed: 'challenge/moves', tier: 3,
    mechanics: { hints: false, undo: true, moveLimit: Math.ceil(t.size ** 2 * 1.05) }, title: 'Challenge — moves',
  });
  const L = header('the Strict ledger challenge (16×16, move limit, no hints) filled without slips to the results,', [
    'then its local leaderboard and Home.']);
  L.push('click =Challenge', 'until 60 Strict ledger', 'frames 10', 'save challenge-setup', 'click =Start', 'until 120 Moves left', 'frames 30');
  const b = new Board(level, L);
  b.fillAll();
  L.push('until 240 Illustration complete', 'frames 30', 'expect Leaderboard rank: #1 (local board)', 'click =Leaderboard', 'until 60 1 entry', 'frames 10', 'save challenge-board', 'click =Close', 'frames 10', 'click =Home', 'until 120 Fill numbered regions');
  write('challenge-ledger.play', L);
}
